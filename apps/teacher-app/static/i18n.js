  const LANG_KEY = "ysl_lang";
  const ENGINE = (document.body && document.body.dataset.engine) || "bili";
  const PACK = DICT[ENGINE] || DICT.bili;
  window.YSLLang = {
    get current() {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === "zh" || saved === "en") return saved;
      // 没主动选过 → 跟随浏览器语言（中文浏览器直接进中文，其它默认英文）
      return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
    },
    set(lang) {
      localStorage.setItem(LANG_KEY, lang === "zh" ? "zh" : "en");
      apply();
      // 只有用户主动切换才派发：apply() 里派发会变成
      // applyEngineLayout → apply → ysl-lang → loadStatus → applyEngineLayout 的死循环
      window.dispatchEvent(new CustomEvent("ysl-lang"));
    },
    /** T("keep_min", {n: 5}) —— 缺 key 时回退到英语，再回退到 key 本身，避免出现空白 */
    T(key, vars) {
      const l = window.YSLLang.current;
      let s = (PACK[l] && PACK[l][key]) || PACK.en[key] || key;
      if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(vars[k]);
      return s;
    },
  };

  function apply() {
    const l = window.YSLLang.current;
    document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
    document.title = window.YSLLang.T("title");
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = window.YSLLang.T(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = window.YSLLang.T(el.dataset.i18nPh);
    });
    const fm = document.getElementById("foot-mode");
    if (fm && !fm.textContent.trim()) fm.textContent = window.YSLLang.T("footer_local");
    document.querySelectorAll("#lang button").forEach((b) => {
      b.classList.toggle("on", b.dataset.lang === l);
    });
  }
  window.YSLLang.apply = apply;

  document.addEventListener("DOMContentLoaded", () => {
    const nav = document.getElementById("lang");
    if (nav) {
      nav.addEventListener("click", (e) => {
        const b = e.target.closest("button[data-lang]");
        if (b) window.YSLLang.set(b.dataset.lang);
      });
    }
    apply();
  });
